begin;

alter table public.chatbot_pdf_file_private
    add column if not exists processing_progress jsonb null;

create unique index if not exists auth_student_email_unique_idx
    on public.auth_student (email);

create table if not exists public.chatbot_student_records (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    student_email text not null references public.auth_student(email) on update cascade on delete cascade,
    source_pdf_id bigint not null references public.chatbot_pdf_file_private(id) on update cascade on delete cascade,
    source_file_name text not null,
    page_numbers integer[] not null default '{}',
    record_count integer not null default 0 check (record_count >= 0),
    records_ciphertext text not null,
    constraint chatbot_student_records_student_source_key unique (student_email, source_pdf_id)
);

create index if not exists chatbot_student_records_student_created_idx
    on public.chatbot_student_records (student_email, created_at desc);

alter table public.chatbot_student_records enable row level security;
revoke all on public.chatbot_student_records from anon, authenticated;
grant all on public.chatbot_student_records to service_role;
grant usage, select on sequence public.chatbot_student_records_id_seq to service_role;

commit;
